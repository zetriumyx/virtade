#!/usr/bin/env python3
"""Rebuild an inventory from Cargo.lock and installed pnpm packages; no network access."""
import json
from pathlib import Path
import tomllib

root = Path(__file__).resolve().parents[1]
registry = Path.home() / '.cargo/registry/src'
rows = []
missing = []
for package in tomllib.loads((root / 'Cargo.lock').read_text())['package']:
    if not package.get('source', '').startswith('registry+'):
        continue
    name, version = package['name'], package['version']
    matches = list(registry.glob(f'*/{name}-{version}/Cargo.toml'))
    metadata = tomllib.loads(matches[0].read_text()).get('package', {}) if matches else {}
    license_name = metadata.get('license', '')
    if not license_name:
        license_name = 'SEE LICENSE FILE' if metadata.get('license-file') else 'UNVERIFIED (source not cached)'
        missing.append(f'{name}@{version}')
    rows.append(('Rust', name, version, license_name, f'https://crates.io/crates/{name}/{version}'))
seen = set()
for pattern in ['*/node_modules/*/package.json', '*/node_modules/@*/*/package.json']:
    for file in (root / 'node_modules/.pnpm').glob(pattern):
        metadata = json.loads(file.read_text())
        name, version = metadata.get('name'), metadata.get('version')
        if not name or not version or (name, version) in seen:
            continue
        seen.add((name, version))
        license_name = metadata.get('license', 'UNVERIFIED (no SPDX field)')
        if isinstance(license_name, dict):
            license_name = license_name.get('type', str(license_name))
        rows.append(('Node', name, version, str(license_name), f'https://www.npmjs.com/package/{name}/v/{version}'))
lines = ['# Third-party dependency inventory', '',
    'Generated by `python3 scripts/third-party-notices.py` from Cargo.lock and the installed pnpm tree. Includes build and test dependencies; platform-only Rust sources may be uncached. SPDX declarations are an inventory, not the complete license notices required for binary distribution. Review UNVERIFIED entries and collect upstream license/NOTICE texts before publishing installers. User-installed Agent executables are separate distributions.', '',
    '| Ecosystem | Package | Version | Declared license | Upstream |',
    '| --- | --- | --- | --- | --- |']
for ecosystem, name, version, license_name, url in sorted(rows):
    safe_license = license_name.replace('|', '\\|').replace('\n', ' ')
    lines.append(f'| {ecosystem} | {name} | {version} | {safe_license} | [source]({url}) |')
(root / 'THIRD_PARTY_NOTICES.md').write_text('\n'.join(lines) + '\n')
print(f'Wrote {len(rows)} dependency declarations; {len(missing)} Rust entries require source/license review.')
